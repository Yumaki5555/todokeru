import { describe, expect, it } from 'vitest';
import { plainEnd, politeEnd, politeText } from '../src/content/polite';

describe('文の終わりを「です・ます」にそろえる', () => {
  it.each([
    // 過去
    ['2つの保育園を1つにすると知った', '2つの保育園を1つにすると知りました'],
    ['夜間に大きな話し声が聞こえた', '夜間に大きな話し声が聞こえました'],
    ['10月1日に騒音があった', '10月1日に騒音がありました'],
    ['説明会が1回だけだった', '説明会が1回だけでした'],
    ['区報に書いてあった', '区報に書いてありました'],
    ['担当課に連絡した', '担当課に連絡しました'],
    ['近所の人から聞いた', '近所の人から聞きました'],
    ['チラシが届いた', 'チラシが届きました'],
    ['担当者がそう言った', '担当者がそう言いました'],
    ['窓口に行った', '窓口に行きました'],
    ['結果がわかった', '結果がわかりました'],
    ['費用が高かった', '費用が高かったです'],
    ['計画書を読んだ', '計画書を読みました'],
    ['方針を決めた', '方針を決めました'],
    ['説明会に参加できた', '説明会に参加できました'],
    ['説明がなかった', '説明がありませんでした'],
    // 今
    ['騒音が続いている', '騒音が続いています'],
    ['説明会は開かれていない', '説明会は開かれていません'],
    ['説明がない', '説明がありません'],
    ['公園に子どもがいる', '公園に子どもがいます'],
    ['来年から始まる', '来年から始まります'],
    ['毎晩音が聞こえる', '毎晩音が聞こえます'],
    ['費用が高い', '費用が高いです'],
    ['説明会を開いてほしい', '説明会を開いてほしいです'],
    ['来年度から統合予定', '来年度から統合予定です'],
    ['住民への説明が不十分だ', '住民への説明が不十分です'],
    ['影響は大きいと思う', '影響は大きいと思います'],
    // 話し言葉の「〜てる」
    ['やさしい日本語に5000万もかかってる', 'やさしい日本語に5000万もかかっています'],
    ['値上がりが続いてる', '値上がりが続いています'],
    ['担当課に何度も連絡してます', '担当課に何度も連絡しています'],
    ['説明会で聞いてた', '説明会で聞いていました'],
    ['まだ返事が来てない', 'まだ返事が来ていません'],
    ['資料を読んでない', '資料を読んでいません'],
    ['ごみを捨てる', 'ごみを捨てます'],
    ['子どもを育てた', '子どもを育てました'],
    // そのままにする
    ['説明会がありました', '説明会がありました'],
    ['よろしくお願いします', 'よろしくお願いします'],
    ['対応してください', '対応してください'],
    ['急いだ', '急いだ'],
  ])('%s → %s', (from, to) => {
    expect(politeEnd(from)).toBe(to);
  });

  it('文ごとにそろえて「。」で終える（「？」で終わる文はそのまま）', () => {
    expect(politeText('騒音があった。近所も困っている\n説明はあるの？')).toBe('騒音がありました。近所も困っています。説明はあるの？');
    expect(politeText('市の公式ページ、条例の名称')).toBe('市の公式ページ、条例の名称です。');
    expect(politeText('  ')).toBe('');
  });
});

describe('文の終わりをふつうの形（〜した・〜ある）にする', () => {
  it.each([
    ['報道がありました', '報道があった'],
    ['説明はありませんでした', '説明はなかった'],
    ['5000万もかかってる', '5000万もかかっている'],
    ['5000万もかかっています', '5000万もかかっている'],
    ['区報で読んでた', '区報で読んでいた'],
    ['連絡しても返事してない', '連絡しても返事していない'],
    ['担当課に連絡しました', '担当課に連絡した'],
    ['担当課は対応しませんでした', '担当課は対応しなかった'],
    ['話し声が聞こえました', '話し声が聞こえた'],
    ['大きな音を聞きました', '大きな音を聞いた'],
    ['日程が決まりました', '日程が決まった'],
    ['説明会ができました', '説明会ができた'],
    ['苦情が増えてきました', '苦情が増えてきた'],
    ['現地に行きました', '現地に行った'],
    ['区報を読みました', '区報を読んだ'],
    ['職員の人がいました', '職員の人がいた'],
    ['説明会が開かれます', '説明会が開かれる'],
    ['費用が高いです', '費用が高い'],
    ['説明会は1回でした', '説明会は1回だった'],
    ['報道があったのです', '報道があった'],
    ['報道があった', '報道があった'],
  ])('%s → %s', (input, expected) => {
    expect(plainEnd(input)).toBe(expected);
  });
});

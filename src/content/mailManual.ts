/** 電話マニュアルの章にある用語の説明（同じデータを使う） */
function phoneTerms(chapterId: string): ManualBlock {
  const block = PHONE_CHAPTERS.find((c) => c.id === chapterId)?.blocks.find((b) => b.kind === 'terms');
  if (!block) throw new Error(`電話マニュアルの ${chapterId} に用語の説明がありません`);
  return block;
}

/** ツールの「困ったときの文例」と同じ文（返事が来ないとき・担当ではないとき・名前を書きたくないとき） */
function helpText(key: 'again' | 'other' | 'name'): string {
  return mailHelpLines(EMPTY_MAIL, '【質問】○○について').find((h) => h.key === key)!.text;
}


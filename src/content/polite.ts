// 入力された文の終わりを「です・ます」にそろえる（電話で読み上げても、ぶっきらぼうに聞こえないように）
// よく使う形だけを直し、自信のない形はそのまま残す。③の台本は、あとから手で直せる。

/** 上から順に試し、最初に当てはまったものだけ使う */
const RULES: [RegExp, string][] = [
  // 話し言葉の「〜てる」「〜てます」→「〜ている」「〜ています」（かかってる・してます）
  // 前が漢字の「捨てる」「育てる」などは当てはまらないようにする
  [/([っいんしえけげせぜねへべめれきぎじちにびみり見出来着寝])([てで])(ます|ました|ません|ませんでした)$/u, '$1$2い$3'],
  [/([っいんしえけげせぜねへべめれきぎじちにびみり見出来着寝])([てで])る$/u, '$1$2います'],
  [/([っいんしえけげせぜねへべめれきぎじちにびみり見出来着寝])([てで])た$/u, '$1$2いました'],
  // 「〜でない」は「好きでない」と見分けられないので「読んでない」の形だけ
  [/([っいんしえけげせぜねへべめれきぎじちにびみり見出来着寝]て|んで)なかった$/u, '$1いませんでした'],
  [/([っいんしえけげせぜねへべめれきぎじちにびみり見出来着寝]て|んで)ない$/u, '$1いません'],
  // すでにていねいな形・言い切らない形はそのまま
  [/(です|ます|ました|でした|ません|ませんでした|ください|下さい|でしょう|ましょう)$/u, '$1'],
  [/だろう$/u, 'でしょう'],
  // 〜だ・〜ではない
  [/(では|じゃ)なかった$/u, 'ではありませんでした'],
  [/(では|じゃ)ない$/u, 'ではありません'],
  [/だった$/u, 'でした'],
  [/である$/u, 'です'],
  // 〜ている・〜てある
  [/([てで])いなかった$/u, '$1いませんでした'],
  [/([てで])いない$/u, '$1いません'],
  [/([てで])いた$/u, '$1いました'],
  [/([てで])いる$/u, '$1います'],
  [/([てで])あった$/u, '$1ありました'],
  [/([てで])ある$/u, '$1あります'],
  // ある・ない・いる
  [/([がはもに])なかった$/u, '$1ありませんでした'],
  [/([がはもに])ない$/u, '$1ありません'],
  [/あった$/u, 'ありました'],
  [/ある$/u, 'あります'],
  [/([がはもに])いた$/u, '$1いました'],
  [/([がはもに])いる$/u, '$1います'],
  // する
  [/しなかった$/u, 'しませんでした'],
  [/しない$/u, 'しません'],
  [/した$/u, 'しました'],
  [/する$/u, 'します'],
  // 〜た（過去）
  [/(わ|分|か|掛|助|見つ|ぶつ|預)かった$/u, '$1かりました'],
  [/かった$/u, 'かったです'], // 高かった・よかった
  [/はいった$/u, 'はいりました'],
  [/(と|って)いった$/u, '$1いいました'],
  [/(行|い)った$/u, '$1きました'],
  [/(言|思|使|払|買|会|違|もら|伺|従|失|拾|洗|迷|誘|習|追|扱|争|戦|吸|笑|奪|補|沿|伴|狙|願|手伝|揃|整|疑)った$/u, '$1いました'],
  [/(待|持|立|勝|打|経|保|育|放|建|絶)った$/u, '$1ちました'],
  [/った$/u, 'りました'], // 知った・なった・決まった
  [/(選|飛|並|運|遊|呼|学|結|喜|転|浴|及|叫)んだ$/u, '$1びました'],
  [/死んだ$/u, '死にました'],
  [/([一-龠々]|し)んだ$/u, '$1みました'], // 読んだ・住んだ・楽しんだ
  [/([一-龠々])いだ$/u, '$1いだ'], // 急いだ・嫌いだ：見分けられないのでそのまま
  [/いた$/u, 'きました'], // 聞いた・届いた
  [/([えけげせぜてでねへべめれきぎじちにびみり見着似煮寝出得])た$/u, '$1ました'], // 聞こえた・決めた・できた
  [/だ$/u, 'です'],
  // 〜い（高い・ほしい・したい）
  [/い$/u, 'いです'],
  // 名詞で終わる
  [/(こと|もの|ところ|とき|ため|など|まで|だけ|ほど|はず|よう|そう)$/u, '$1です'],
  [/([一-龠々ァ-ヶーa-zA-Z0-9０-９ａ-ｚＡ-Ｚ%％])$/u, '$1です'],
  // 〜る・〜う など（言い切りの形）
  [/てくる$/u, 'てきます'],
  [/来る$/u, '来ます'],
  [/([えけげせぜてでねへべめれきぎじちにびみり見着似煮寝出得])る$/u, '$1ます'], // 考える・できる
  [/う$/u, 'います'],
  [/く$/u, 'きます'],
  [/ぐ$/u, 'ぎます'],
  [/す$/u, 'します'],
  [/つ$/u, 'ちます'],
  [/ぬ$/u, 'にます'],
  [/ぶ$/u, 'びます'],
  [/む$/u, 'みます'],
  [/る$/u, 'ります'],
];

/** 1つの文（句点なし）の終わりを「です・ます」にする */
export function politeEnd(s: string): string {
  for (const [re, to] of RULES) {
    if (re.test(s)) return s.replace(re, to);
  }
  return s;
}

/** 句点や改行で文に分ける（文の終わりの「、」や空白は取る） */
export function splitSentences(s: string): string[] {
  return s
    .split(/[。．\n]+/u)
    .map((x) => x.trim().replace(/[、，,\s]+$/u, ''))
    .filter(Boolean);
}

/** 句点や改行で文に分け、それぞれの終わりをそろえて「。」で終える */
export function politeText(s: string): string {
  return splitSentences(s)
    .map((x) => (/[！!？?]$/u.test(x) ? x : politeEnd(x) + '。'))
    .join('');
}

// ここから下は逆向き：「〜ことです」「〜かを確認したいです」の中に入れるため、文の終わりをふつうの形（〜した・〜ある）にする

/** 話し言葉の「〜てる」と見分けるための、「て・で」の前に来る音（上の決まりと同じ） */
const TE_BEFORE = '[っいんしえけげせぜねへべめれきぎじちにびみり見出来着寝]';

/** 話し言葉「〜てる」「〜てます」「〜てない」→「〜ている」「〜ています」「〜ていない」 */
const COLLOQUIAL: [RegExp, string][] = [
  [new RegExp(`(${TE_BEFORE})([てで])(ます|ました|ません|ませんでした)$`, 'u'), '$1$2い$3'],
  [new RegExp(`(${TE_BEFORE})([てで])(る|た)$`, 'u'), '$1$2い$3'],
  [new RegExp(`(${TE_BEFORE}て|んで)(ない|なかった)$`, 'u'), '$1い$2'],
];

/** 「ます」の前の音 → [言い切り, 〜た, 〜ない の前]（「書きます」→「書く」「書いた」「書かない」）。「し」は「する」として扱う */
const GODAN: Record<string, [string, string, string]> = {
  い: ['う', 'った', 'わ'],
  き: ['く', 'いた', 'か'],
  ぎ: ['ぐ', 'いだ', 'が'],
  し: ['する', 'した', 'し'],
  ち: ['つ', 'った', 'た'],
  に: ['ぬ', 'んだ', 'な'],
  び: ['ぶ', 'んだ', 'ば'],
  み: ['む', 'んだ', 'ま'],
  り: ['る', 'った', 'ら'],
};

/** 「見ます」「できます」「決めます」「人がいます」「しています」のように、そのまま「る」「た」「ない」がつく形 */
const ICHIDAN = /([えけげせぜてでねへべめれじ]|[見着寝出似煮得来]|(?<!お)[がはもにてで]い|でき|起き|生き|過ぎ|落ち|満ち|延び|伸び|浴び|借り|降り|下り|足り|用い|試み)$/u;

/** 「ます」「ました」「ません」「ませんでした」の前（語幹）から、ふつうの形を作る。見分けられない形は null */
function plainVerb(stem: string, end: string): string | null {
  const neg = end.startsWith('ません');
  const past = end === 'ました' || end === 'ませんでした';
  const negEnd = past ? 'なかった' : 'ない';
  // ありません →ない
  if (/あり$/u.test(stem)) return neg ? stem.slice(0, -2) + negEnd : stem.slice(0, -1) + (past ? 'った' : 'る');
  // 増えてきます →増えてくる
  if (/(て|んで)き$/u.test(stem)) return stem.slice(0, -1) + (neg ? 'こ' + negEnd : past ? 'きた' : 'くる');
  if (ICHIDAN.test(stem)) return stem + (neg ? negEnd : past ? 'た' : 'る');
  const g = GODAN[stem.slice(-1)];
  if (!g) return null;
  const base = stem.slice(0, -1);
  if (neg) return base + g[2] + negEnd;
  if (past) return base + (/(行|い)き$/u.test(stem) ? 'った' : g[1]); // 行きました →行った
  return base + g[0];
}

/** 1つの文（句点なし）の終わりを、ふつうの形にする（「報道がありました」→「報道があった」、「高いです」→「高い」）。見分けられない形は null */
export function plainEnd(s: string): string | null {
  const rule = COLLOQUIAL.find(([re]) => re.test(s));
  const t = rule ? s.replace(rule[0], rule[1]) : s;
  const m = t.match(/^(.*?)(ませんでした|ません|ました|ます)$/u);
  if (m) return plainVerb(m[1], m[2]);
  if (/でした$/u.test(t)) return t.replace(/でした$/u, 'だった');
  return t.replace(/(な?[のん])?です$/u, '');
}

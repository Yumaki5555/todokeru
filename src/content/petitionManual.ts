export const templateText = () => {
  const t = PETITION_TEMPLATE;
  return [
    `【${t.heading}】`,
    t.to,
    t.itemsTitle,
    t.items.map((x, i) => `${i + 1}. ${x}`).join('\n'),
    t.reasonTitle,
    t.reason.join('\n'),
    t.footer.join('\n'),
  ].join('\n\n');
};

